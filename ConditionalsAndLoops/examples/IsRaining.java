package ConditionalsAndLoops.examples;

public class IsRaining {
    public static void main(String[] args) {
        boolean isRaining = true;

        if (isRaining) {
            System.out.println("It's raining. Don't forget your umbrella!");
        } else {
            System.out.println("It's not raining. Enjoy your day!");
        }
    }
}
